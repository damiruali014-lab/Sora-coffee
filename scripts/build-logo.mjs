// One-off: converts the "sora" wordmark (Unbounded 700) into outline paths so the logo
// renders identically everywhere, without depending on the web font. Output: src/components/logo-paths.ts
import opentype from 'opentype.js'
import { readFileSync, writeFileSync } from 'node:fs'

const buf = readFileSync('node_modules/@fontsource/unbounded/files/unbounded-latin-700-normal.woff')
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))
const size = 100
const scale = size / font.unitsPerEm
const tracking = -2

let x = 0
const glyphs = []
for (const ch of 'sora') {
  const g = font.charToGlyph(ch)
  const bb = g.getPath(x, 0, size).getBoundingBox()
  glyphs.push({ ch, d: g.getPath(x, 0, size).toPathData(2), bb })
  x += g.advanceWidth * scale + tracking
}
const minY = Math.min(...glyphs.map((g) => g.bb.y1))
const maxY = Math.max(...glyphs.map((g) => g.bb.y2))
const minX = glyphs[0].bb.x1
const o = glyphs[1].bb
const out = {
  d: glyphs.map((g) => g.d).join(''),
  box: [minX, minY, glyphs.at(-1).bb.x2 - minX, maxY - minY].map((n) => +n.toFixed(2)),
  o: { cx: +((o.x1 + o.x2) / 2).toFixed(2), top: +o.y1.toFixed(2), w: +(o.x2 - o.x1).toFixed(2) },
}
writeFileSync('src/components/logo-paths.ts', `// Generated by scripts/build-logo.mjs — do not edit by hand.\nexport const WORDMARK = ${JSON.stringify(out)} as const\n`)
